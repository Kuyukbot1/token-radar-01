// Token Radar model "radar-2": one sealed snapshot in, one ranked board out.
//
// The board ranks EVERY protocol that records no token and is not a wrapped,
// staked or bridged product of a token that already trades. That is the
// watchlist (40 protocols at or above the $50M floor) plus every protocol
// below the floor that passes the same rule, plus the few above the floor the
// house list leaves out. Wrapped / staked / bridged products (WBTC, Binance
// staked ETH, USDT0, bridges, liquid-staking wrappers) are never ranked:
// they are not launches waiting to happen.
//
// A protocol "records no token" when its snapshot entry has no market cap, no
// CoinGecko id and no symbol. The snapshot is DefiLlama's record, not proof,
// so the board and the dashboard always say "records no token", never that a
// protocol "has no token".
//
// Implied value is derived only from the snapshot's own figures, by one
// function applied to every row. No protocol name is ever special-cased.
//
//   catMultiple  = median(mcap_usd / tvl_usd) over live-token protocols in
//                  the same category, when at least 4 such peers exist;
//                  otherwise the global median over all live-token
//                  protocols. Clamped to [0.05, 1.00]. A category's own
//                  market is its own comparable: DEX tokens trade at a
//                  different multiple of TVL than lending tokens do.
//   base         = tvl_usd * catMultiple
//   growth       = clamp(change_7d, -50, 100) per cent (null -> 0)
//   growthMult   = 1 + (growth / 100) * 0.60
//   age_days     = days from listed_at to as_of (null -> 365)
//   maturityMult = 0.65 + min(age_days, 1095) / 1095 * 0.35
//   reachMult    = 1 + 0.02 * min(chains - 1, 8)   (multi-chain reach)
//   implied      = max(1, round(base * growthMult * maturityMult * reachMult))
//
// Live-token protocols are kept apart: the dashboard shows the top ones by
// market cap as the market's own values, never mixed into the ranking.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

